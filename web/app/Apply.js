"use client";

import { useState } from "react";
import { copyText } from "./useAction";
import { chipsOf, verdictOf } from "@/lib/blockers";
import { VARIANTS } from "@/lib/variant";

/**
 * The apply packs: everything drafted for a role, ready to paste.
 *
 * WHY THIS PAGE EXISTS. The pipeline finds and scores roles well and then stops.
 * What stands between a 60+ role and a submitted application is an evening of
 * writing, and that evening is why `applications` held zero rows on the day this
 * was built. The pack removes the blank page. It does not apply for him.
 *
 * NOTHING HERE SENDS. Every field is a textarea and a copy button. The copy
 * records that THE OWNER copied it, because the paste into a real application form
 * is the approval — the same gate the outreach drafts use.
 *
 * A DRAFT IS NOT A SUBMISSION, and the page says so rather than letting a wall
 * of finished-looking text imply otherwise. Every one of these needs reading and
 * editing before it goes anywhere near a recruiter.
 */

const FIELDS = [
  ["cover_note", "Cover note"],
  ["why_company", "Why this company"],
  ["why_role", "Why this role"],
  ["project_story", "A project you built"],
  ["biggest_challenge", "Biggest challenge"],
];

function Field({ label, text, onCopy }) {
  const [state, setState] = useState("idle");
  const [err, setErr] = useState(null);

  async function copy() {
    setErr(null);
    // THE CLIPBOARD FIRST. Recording a pack as used when the text never reached
    // the clipboard would make the untouched count lie in the one direction
    // that matters.
    if (!(await copyText(text || ""))) {
      setErr("Couldn't reach the clipboard. Select the text and copy it by hand.");
      return;
    }
    setState("copied");
    try {
      await onCopy();
    } catch (e) {
      // The text IS on the clipboard. Say what actually failed.
      setErr(`Copied, but the use wasn't recorded: ${e.message}`);
    }
  }

  if (!text) return null;
  return (
    <div className="pfield">
      <div className="phead">
        <span className="pname">{label}</span>
        <span className="pmeta">{text.trim().split(/\s+/).length} words</span>
        <span className="pwhen" />
        <span className="pacts">
          <button type="button" className="act" onClick={copy}>
            {state === "copied" ? "Copied" : "Copy"}
          </button>
        </span>
      </div>
      <textarea className="ptext" defaultValue={text} rows={Math.min(10,
        Math.ceil(text.length / 90) + 1)} />
      {err && <p className="nothing">{err}</p>}
    </div>
  );
}

export default function Apply({ packs = [] }) {
  const [open, setOpen] = useState(null);
  const [used, setUsed] = useState({});

  async function markUsed(key) {
    const r = await fetch("/api/packs", {
      method: "POST",
      headers: { "content-type": "application/json" },
      body: JSON.stringify({ key }),
    });
    if (!r.ok) throw new Error((await r.json().catch(() => ({})))?.error || `HTTP ${r.status}`);
    setUsed((u) => ({ ...u, [key]: true }));
  }

  // A ROW WITH NO COVER NOTE IS NOT A PACK. 92 of the first 124 responses hit
  // max_tokens and never produced parseable JSON; their raw is kept so nothing
  // is lost, but counting them as packs would report 124 where 32 exist. Two
  // numbers on one row must come from one population.
  const real = packs.filter((p) => p.cover_note);
  const failed = packs.length - real.length;
  const opened = real.filter((p) => p.used_at || used[p.key]).length;

  return (
    <>
      <h1>Apply</h1>

      {!packs.length ? (
        // AN EMPTY PAGE IS EITHER "none generated yet" OR "the table is
        // unreachable", and those read identically unless one of them says so.
        <p className="nothing">
          No packs yet. They are generated by <code>python apply_packs.py</code>{" "}
          for open roles scoring 60+ whose blockers are clear. If you expected
          some, that command has not run rather than there being nothing to do.
        </p>
      ) : (
        <>
          <p className="counter">
            {real.length} packs · {opened} opened · {real.length - opened} untouched
            {failed > 0 && (
              <> · <strong>{failed} did not parse</strong>, raw kept, rerun{" "}
                <code>apply_packs.py</code> to redraft them</>
            )}
          </p>
          <p className="sub">
            Drafts, not submissions. Read and edit every one before it goes
            anywhere. Copying a field marks the pack as opened.
          </p>

          <div className="section">
            {packs.map((p) => {
              const isOpen = open === p.key;
              const chips = chipsOf(p);
              const v = p.variant ? VARIANTS[p.variant] : null;
              const isUsed = p.used_at || used[p.key];
              return (
                <div key={p.key} className="person">
                  <div className="phead">
                    <span className="pname">{p.display_name}</span>
                    <span className="pmeta">
                      {p.title}
                      {p.score ? ` · ${p.score}` : ""}
                    </span>
                    <span className="pwhen">{isUsed ? "opened" : "untouched"}</span>
                    <span className="pacts">
                      {p.url && (
                        <a className="act" href={p.url} target="_blank"
                           rel="noreferrer noopener">Apply</a>
                      )}
                      <button type="button" className="act"
                              onClick={() => setOpen(isOpen ? null : p.key)}>
                        {isOpen ? "Hide pack" : "Pack"}
                      </button>
                    </span>
                  </div>

                  {(chips.length > 0 || verdictOf(p) === "unknown") && (
                    <p className="chips">
                      {chips.map((c) => (
                        <span key={c.tag}
                              className={c.hard ? "chip chip-hard" : "chip chip-ok"}
                              title={c.explain}>{c.label}</span>
                      ))}
                    </p>
                  )}

                  {isOpen && (
                    <div className="sub">
                      {/* THE VARIANT WAS CHOSEN IN CODE. The model wrote the
                          reason for a decision it did not make, and a pack with
                          no rule for its category says so rather than showing a
                          guessed tag. */}
                      <p className="note">
                        {v
                          ? <><strong>Send the {v.label} resume.</strong> {p.variant_reason}</>
                          : <><strong>No resume rule for this company&rsquo;s category.</strong>{" "}
                              Pick by hand; nothing here guessed one.</>}
                      </p>

                      {p.raw && (
                        // FAIL OPEN: the response did not parse, and the raw
                        // text is kept rather than dropped. It is already paid
                        // for, and it is still evidence of what came back.
                        <p className="nothing">
                          This pack did not parse into fields. The raw response is
                          stored; regenerate it with{" "}
                          <code>python apply_packs.py submit</code>.
                        </p>
                      )}

                      {FIELDS.map(([f, label]) => (
                        <Field key={f} label={label} text={p[f]}
                               onCopy={() => markUsed(p.key)} />
                      ))}
                    </div>
                  )}
                </div>
              );
            })}
          </div>
        </>
      )}
    </>
  );
}
