/**
 * Bake the resume files into the bundle at BUILD time. Run by `prebuild`/`predev`.
 *
 * SEPARATE FROM genconfig.mjs on purpose. This started inside it and broke
 * test_config.mjs, which runs the generator against a THROWAWAY TREE holding a
 * config.yaml and nothing else — a fair fixture for a config generator, and one
 * that cannot satisfy a generator that also demands two PDFs and two markdown
 * files. The fix is not to soften either failure; it is that a generator should
 * fail on its OWN inputs. Two generators, two sets of required files, two
 * fixtures that stay honest.
 *
 * Everything here is read at build time for the reason genconfig.mjs documents
 * at length: a value that must reach production cannot travel by filesystem at
 * request time. cost.js read config.yaml inside a function, the tracer never saw
 * it, and the deployed cost meter showed the lifetime total as this month's
 * spend. /resumes is exactly the page where a wrong number would be worst — its
 * whole job is telling the owner which version of the document is live.
 */
import fs from "node:fs";
import path from "node:path";
import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));      // web/lib
const RESUME_DIR = path.join(here, "..", "public", "resume");
const DEST = path.join(here, "resumes.generated.js");

const FILES = {
  tech: "resume-tech.pdf",
  finance: "resume-finance.pdf",
};

function die(msg, fix) {
  console.error(`\ngenresumes: ${msg}\n`);
  if (fix) console.error(`  ${fix}\n`);
  process.exit(1);
}

const RESUMES = {};
for (const [variant, file] of Object.entries(FILES)) {
  const pdf = path.join(RESUME_DIR, file);
  if (!fs.existsSync(pdf)) {
    // A missing resume is a broken page, not a smaller one.
    die(`${file} is missing from web/public/resume/.`,
        `Put it back with: git restore web/public/resume/${file}`);
  }
  const md = path.join(here, "..", "..", `resume_${variant}.md`);
  if (!fs.existsSync(md)) {
    die(`resume_${variant}.md is missing.`,
        `Regenerate it: python resume_from_pdf.py install <src.pdf> ${variant}`);
  }

  const bytes = fs.statSync(pdf).size;
  const hash = createHash("sha256").update(fs.readFileSync(pdf)).digest("hex").slice(0, 8);

  // THE GIT COMMIT DATE, not the mtime. A fresh clone's mtime is the checkout,
  // so on Vercel every resume would read as "changed at build time" — a
  // confident lie on the one page whose job is saying which version is live.
  // When git cannot answer (a shallow CI clone with a single commit) this stays
  // NULL and the page says "date unavailable" rather than inventing one.
  let modified = null;
  try {
    const out = execFileSync(
      "git", ["log", "-1", "--format=%cI", "--", `public/resume/${file}`],
      { cwd: path.join(here, ".."), encoding: "utf8" }).trim();
    modified = out || null;
  } catch {
    modified = null;
  }

  RESUMES[variant] = {
    file, bytes, hash, modified,
    markdown: fs.readFileSync(md, "utf8"),
  };
}

fs.writeFileSync(
  DEST,
  [
    "/* GENERATED by lib/genresumes.mjs from web/public/resume/*.pdf and the",
    " * resume_*.md beside them. Do not edit, do not commit. */",
    `export const RESUMES = ${JSON.stringify(RESUMES, null, 2)};`,
    "",
  ].join("\n"),
  { encoding: "utf8" },
);

console.log("genresumes: " + Object.entries(RESUMES)
  .map(([v, r]) => `${v} ${r.hash} ${r.modified ? r.modified.slice(0, 10) : "no-date"} `
                 + `(${(r.bytes / 1024).toFixed(0)} KB, ${r.markdown.length} md chars)`)
  .join(", ") + " -> lib/resumes.generated.js");
